
-- ============================================
-- STUDENT INTERNSHIP TRACKER
-- Oracle Database XE
-- Database Schema
-- ============================================

-- 1. STUDENT TABLE
CREATE TABLE INTERNSHIP_STUDENTS (
    SID NUMBER(10) PRIMARY KEY,
    SNAME VARCHAR2(100) NOT NULL,
    SEMAIL VARCHAR2(150) NOT NULL,
    SADDR VARCHAR2(250),
    PHNO VARCHAR2(20),
    PASSWORD_HASH VARCHAR2(500) NOT NULL,

    CONSTRAINT UQ_STUDENT_EMAIL UNIQUE (SEMAIL)
);


-- 2. INTERNSHIP APPLICATION SEQUENCE
CREATE SEQUENCE INTERNSHIP_APP_SEQ
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;


-- 3. INTERNSHIP APPLICATIONS TABLE
CREATE TABLE INTERNSHIP_APPLICATIONS (
    APPLICATION_ID NUMBER(10) PRIMARY KEY,
    SID NUMBER(10) NOT NULL,
    COMPANY_NAME VARCHAR2(150) NOT NULL,
    ROLE_NAME VARCHAR2(150) NOT NULL,
    APPLY_DATE DATE DEFAULT SYSDATE,
    JOB_LOCATION VARCHAR2(150),
    WORK_MODE VARCHAR2(50),
    STIPEND NUMBER(12,2),
    APPLICATION_STATUS VARCHAR2(50) DEFAULT 'Applied',
    APPLICATION_LINK VARCHAR2(1000),
    NOTES VARCHAR2(1000),

    CONSTRAINT FK_APPLICATION_STUDENT
        FOREIGN KEY (SID)
        REFERENCES INTERNSHIP_STUDENTS(SID)
);


-- 4. INTERNSHIP OFFER SEQUENCE
CREATE SEQUENCE INTERNSHIP_OFFER_SEQ
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;


-- 5. INTERNSHIP OFFERS TABLE
CREATE TABLE INTERNSHIP_OFFERS (
    OFFER_ID NUMBER(10) PRIMARY KEY,
    APPLICATION_ID NUMBER(10) NOT NULL,
    SID NUMBER(10) NOT NULL,
    COMPANY_NAME VARCHAR2(150) NOT NULL,
    JOB_ROLE VARCHAR2(150),
    OFFER_TYPE VARCHAR2(50),
    MONTHLY_STIPEND NUMBER(12,2) DEFAULT 0,
    ANNUAL_CTC NUMBER(14,2) DEFAULT 0,
    OFFER_DATE DATE,
    JOINING_DATE DATE,
    OFFER_STATUS VARCHAR2(50),
    NOTES VARCHAR2(500),

    CONSTRAINT FK_OFFER_STUDENT
        FOREIGN KEY (SID)
        REFERENCES INTERNSHIP_STUDENTS(SID),

    CONSTRAINT FK_OFFER_APPLICATION
        FOREIGN KEY (APPLICATION_ID)
        REFERENCES INTERNSHIP_APPLICATIONS(APPLICATION_ID)
);


